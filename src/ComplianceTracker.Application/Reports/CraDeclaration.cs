namespace ComplianceTracker.Application.Reports
{
    // What the tracker knows about a CRA product for its EU declaration of conformity. Null means "not known".
    public sealed record CraProduct(
        string Name, string? Version, string? IntendedPurpose, string Manufacturer, string? Cvr, string? Country, string? ClassCode,
        IReadOnlyList<string> AppliedRequirements);

    // US-181: a draft EU declaration of conformity (CRA Art. 28, Annex V) filled in from the tracker. Every item of Annex V is
    // there; what the tracker does not know says "To be completed" (R2). Pure, so the edge cases are tested on their own.
    public static class CraDeclaration
    {
        public const string FileName = "CRA-declaration-of-conformity.pdf";
        public const string TechnicalDocumentationFileName = "CRA-technical-documentation.pdf";
        public const string ToBeCompleted = "To be completed";
        public const string DraftNotice = "Draft generated by the compliance tracker; to be reviewed and signed by the manufacturer.";

        // R3: the conformity assessment procedure the class allows (CRA Art. 32)
        public static string? Module(string? classCode) => classCode switch
        {
            "Default" => "Module A (internal control), or module B+C or H",
            "ImportantClassI" => "Module B+C or H, or harmonised standards with module A (Art. 32(2))",
            "ImportantClassII" => "Module B+C or H, or a European cybersecurity certification scheme (Art. 32(3))",
            "Critical" => "A European cybersecurity certificate where required under Art. 8(1); otherwise as class II: module B+C or H (Art. 32(4))",
            _ => null
        };

        // Whether a notified body takes part (not with module A alone)
        public static bool MayNeedNotifiedBody(string? classCode) => classCode is "ImportantClassI" or "ImportantClassII" or "Critical";

        // R2, R3: the fields to complete, e.g. "Version", "Manufacturer's address"; listed by the package's check (US-178)
        public static IReadOnlyList<string> Missing(CraProduct product)
        {
            var missing = new List<string>();
            if (string.IsNullOrWhiteSpace(product.Version))
            {
                missing.Add("Version");
            }

            if (string.IsNullOrWhiteSpace(product.IntendedPurpose))
            {
                missing.Add("Intended purpose");
            }

            missing.Add("Manufacturer's address");
            if (Module(product.ClassCode) is null)
            {
                missing.Add("Conformity assessment procedure: classify the product");
            }

            if (product.AppliedRequirements.Count == 0)
            {
                missing.Add("Harmonised standards, common specifications or certification applied");
            }

            if (MayNeedNotifiedBody(product.ClassCode) || Module(product.ClassCode) is null)
            {
                missing.Add("Notified body and certificate, where one took part");
            }

            missing.Add("Place and date of issue, name, function and signature");
            return missing;
        }

        // R2, R4: every item of Annex V, in its order; never presented as signed
        public static GeneratedDocument Build(CraProduct product)
        {
            static string Or(string? value, string what = ToBeCompleted) => string.IsNullOrWhiteSpace(value) ? what : value.Trim();
            var module = Module(product.ClassCode);
            var blocks = new List<DocumentBlock>
            {
                new(DocumentBlockKind.Title, "EU declaration of conformity (draft)"),
                new(DocumentBlockKind.Paragraph, DraftNotice),
                new(DocumentBlockKind.Paragraph, "Regulation (EU) 2024/2847 (Cyber Resilience Act), Article 28 and Annex V."),

                new(DocumentBlockKind.Heading2, "1. Product with digital elements"),
                new(DocumentBlockKind.Bullet, $"Name: {Or(product.Name)}"),
                new(DocumentBlockKind.Bullet, $"Version: {Or(product.Version)}"),
                new(DocumentBlockKind.Bullet, $"Intended purpose: {Or(product.IntendedPurpose)}"),
                new(DocumentBlockKind.Bullet, "Additional information for its unique identification: " + ToBeCompleted),

                new(DocumentBlockKind.Heading2, "2. Manufacturer or authorised representative"),
                new(DocumentBlockKind.Bullet, $"Name: {Or(product.Manufacturer)}"),
                new(DocumentBlockKind.Bullet, $"Address: {ToBeCompleted}{(string.IsNullOrWhiteSpace(product.Country) ? "" : $" (country: {product.Country})")}"),
                new(DocumentBlockKind.Bullet, $"Company registration number: {Or(product.Cvr)}"),

                new(DocumentBlockKind.Heading2, "3. Responsibility"),
                new(DocumentBlockKind.Paragraph, "This declaration of conformity is issued under the sole responsibility of the manufacturer."),

                new(DocumentBlockKind.Heading2, "4. Object of the declaration"),
                new(DocumentBlockKind.Paragraph, $"{Or(product.Name)}, version {Or(product.Version)}. Identification allowing traceability (and a picture, where appropriate): {ToBeCompleted}."),

                new(DocumentBlockKind.Heading2, "5. Conformity"),
                new(DocumentBlockKind.Paragraph, "The object of the declaration described above is in conformity with Regulation (EU) 2024/2847 "
                    + "and with other relevant Union harmonisation legislation providing for its affixing: " + ToBeCompleted + "."),

                new(DocumentBlockKind.Heading2, "6. Harmonised standards, common specifications or certification"),
            };
            blocks.AddRange(product.AppliedRequirements.Count == 0
                ? [new DocumentBlock(DocumentBlockKind.Paragraph, ToBeCompleted)]
                : product.AppliedRequirements.Select(r => new DocumentBlock(DocumentBlockKind.Bullet, r)));
            blocks.Add(new(DocumentBlockKind.Paragraph, "References to the harmonised standards used, with their versions: " + ToBeCompleted + "."));

            blocks.Add(new(DocumentBlockKind.Heading2, "7. Conformity assessment"));
            blocks.Add(new(DocumentBlockKind.Bullet, $"Class: {(product.ClassCode is { } code && module is not null ? Title(code) : ToBeCompleted + ": classify the product")}"));
            blocks.Add(new(DocumentBlockKind.Bullet, $"Procedure: {module ?? ToBeCompleted + ": classify the product"}"));
            blocks.Add(new(DocumentBlockKind.Bullet, MayNeedNotifiedBody(product.ClassCode) || module is null
                ? $"Notified body (name and number), the procedure it performed and its certificate: {ToBeCompleted}, where one took part"
                : "Notified body: not applicable with module A (internal control)"));

            blocks.Add(new(DocumentBlockKind.Heading2, "8. Additional information"));
            blocks.Add(new(DocumentBlockKind.Bullet, $"Signed for and on behalf of: {Or(product.Manufacturer)}"));
            blocks.Add(new(DocumentBlockKind.Bullet, $"Place and date of issue: {ToBeCompleted}"));
            blocks.Add(new(DocumentBlockKind.Bullet, $"Name, function: {ToBeCompleted}"));
            blocks.Add(new(DocumentBlockKind.Bullet, "Signature: not signed (draft)"));
            return new GeneratedDocument(FileName, blocks);
        }

        public static string Title(string classCode) => classCode switch
        {
            "Default" => "Default (not important or critical)",
            "ImportantClassI" => "Important, class I",
            "ImportantClassII" => "Important, class II",
            "Critical" => "Critical",
            _ => classCode
        };

        // US-178: the lines the package's check adds for the declaration
        public static string CheckText(CraProduct product)
            => "CRA declaration of conformity (draft)" + "\n" + string.Concat(Missing(product).Select(m => $"  [ ] {m}: {ToBeCompleted}\n"));
    }
}
